// Shared normalization for Django notifications and optional mock records.
// Django uses is_read; demo records may have status: "Unread" or "Read".
export const isNotificationUnread = (row) => {
  if (typeof row?.is_read === 'boolean') return !row.is_read;
  if (typeof row?.isRead === 'boolean') return !row.isRead;
  return String(row?.status || '').toLowerCase() === 'unread';
};

export const isCustomerEstimateResponse = row =>
  /^customer_estimate_(accepted|declined)$/.test(
    String(row?.notification_type || row?.notificationType || '')
  );

export const unreadNotificationCount = rows =>
  (Array.isArray(rows) ? rows : []).filter(isNotificationUnread).length;

export const normalizeNotification = (row = {}) => {
  const data = row.data && typeof row.data === 'object' && !Array.isArray(row.data)
    ? row.data : {};
  const type = String(row.notification_type || row.notificationType || '');
  const attendanceAlert = type.startsWith('attendance_');
  const estimateResponse = isCustomerEstimateResponse(row);
  const priority = row.priority ||
    (estimateResponse || ['attendance_leave_request', 'attendance_overtime_request',
      'attendance_missing_punch'].includes(type) ? 'High' : 'Normal');

  // These links are generated by the backend, not by customers. Preserve
  // route format and reject malformed paths for customer estimate decisions.
  const candidateRoute = row.route || data.route || '';
  const responseRoute = typeof candidateRoute === 'string' &&
    /^\/jobs\/[0-9a-f-]{36}\/estimate$/i.test(candidateRoute)
      ? candidateRoute : '';

  return {
    ...row,
    title: typeof row.title === 'string' ? row.title : 'Notification',
    description: typeof row.description === 'string'
      ? row.description : String(row.message || ''),
    category: estimateResponse ? 'Customer Responses'
      : row.category || (attendanceAlert ? 'Approvals & People' : 'Operational'),
    priority,
    reference: row.reference || (estimateResponse ? data.jobNumber : '') ||
      data.requestId || data.recordId || '',
    status: isNotificationUnread(row) ? 'Unread' : 'Read',
    created: row.created || row.created_at || row.createdAt || '',
    route: estimateResponse ? responseRoute : candidateRoute,
    isCustomerEstimateResponse: estimateResponse,
    customerEstimateDecision: estimateResponse ? data.decision || '' : '',
    receiptId: estimateResponse ? data.receiptId || '' : '',
  };
};
